"""
fake_planner.py

Stands in for a real planning model. A real planner would read a goal
and the available tools, then generate a Plan on its own. This fake
planner follows a fixed script keyed on the goal string instead, so
every demo in this folder is fully repeatable with no API key.

Two goals are scripted: one whose plan runs cleanly end to end, and one
whose plan includes a step that will fail at execution time, so
replanning.py has a real failure to recover from.
"""

from plan_structure import Plan, Step


def fake_plan(goal):
    """
    Returns a scripted Plan for a known goal string. A real planner
    call would take the same single argument (the goal) and return the
    same Plan shape, just generated by an actual model instead of a
    fixed lookup.
    """
    if goal == "handle damaged order 1001":
        return Plan(
            goal=goal,
            steps=[
                Step("s1", "Look up the order", "lookup_order", {"order_id": "ORD-1001"}),
                Step("s2", "Check refund eligibility", "check_refund_eligibility", {"order_id": "ORD-1001"}, depends_on=["s1"]),
                Step("s3", "Create a ticket for the damage", "create_ticket", {"issue": "Order ORD-1001 arrived damaged", "priority": "high"}, depends_on=["s2"]),
            ],
        )

    if goal == "handle damaged order 9999":
        # ORD-9999 does not exist in support_tools.py's ORDERS dict, so
        # lookup_order will come back with ok: False. This is the
        # scripted "a step fails" scenario replanning.py recovers from.
        return Plan(
            goal=goal,
            steps=[
                Step("s1", "Look up the order", "lookup_order", {"order_id": "ORD-9999"}),
                Step("s2", "Check refund eligibility", "check_refund_eligibility", {"order_id": "ORD-9999"}, depends_on=["s1"]),
                Step("s3", "Create a ticket for the damage", "create_ticket", {"issue": "Order ORD-9999 arrived damaged", "priority": "high"}, depends_on=["s2"]),
            ],
        )

    if goal == "handle damaged order 9999 (revised after failure)":
        # The replanned version: skips re-checking the bad order id,
        # and goes straight to logging the problem instead.
        return Plan(
            goal=goal,
            steps=[
                Step("s1", "Create a ticket noting the order could not be found", "create_ticket", {"issue": "Customer reports damaged order ORD-9999, but no such order exists in our system", "priority": "high"}),
            ],
        )

    raise ValueError(f"The fake planner has no scripted plan for goal: '{goal}'.")


def main():
    print("=== Fake Planner ===\n")

    for goal in ("handle damaged order 1001", "handle damaged order 9999"):
        plan = fake_plan(goal)
        print(f"Goal: {plan.goal}")
        for step in plan.steps:
            print(f"  [{step.step_id}] {step.description} -> {step.tool_name}({step.arguments}) depends_on={step.depends_on}")
        print()

    print(
        "This stands in for a real planning model: given a goal and a "
        "list of available tools, a real planner would reason about which "
        "tools apply and in what order, then return a Plan with exactly "
        "this shape. Scripting the response here trades that reasoning "
        "away for repeatability, so the rest of this folder's demos never "
        "depend on an API key or produce a different plan on a different run."
    )


if __name__ == "__main__":
    main()
